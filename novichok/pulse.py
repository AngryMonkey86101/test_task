@dataclass
class Assessment:
    score: int
    level: str
    topics: list[str]
    about_manager: bool


def assess(checkpoint: int, option_indexes: dict[str, int]) -> Assessment:
    score = 0
    red = False
    topics: list[str] = []
    about_manager = False
    for q in CHECKPOINTS[checkpoint]:
        if q.id not in option_indexes:
            continue
        s = q.options[option_indexes[q.id]].score
        score += s
        if s >= 3:
            red = True
        if s >= 1:
            topics.append(q.topic)
            about_manager |= q.about_manager and s >= 3
    level = "red" if red else "yellow" if score >= 2 else "green"
    return Assessment(score, level, topics if level != "green" else [], about_manager)


def due_checkpoint(day: int) -> int | None:
    """Самая поздняя контрольная точка, до которой сотрудник уже дошёл."""
    due = [d for d in CHECKPOINT_DAYS if d <= day]
    return due[-1] if due else None
